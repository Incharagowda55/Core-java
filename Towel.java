class Towel{
	String material;
    String color;
    String brand;
    String size;
    double length;
    double width;
    double weight;
    boolean soft;
    boolean absorbent;
    String pattern;
    int price;
    String dryingSpeed;

   public Towel(String material,String color){
	   this.material=material;
   }
   public Towel(String color){
	   this.color=color;
   }
   public Towel(String brand){
	   this.brand=brand;
   }
   public Towel(String size){
	   this.size=size;
   }
   public Towel(double length){
	   this.length=length;
   }
   public Towel(double width){
	   this.width=width;
   }
   public Towel(boolean soft){
	   this.soft=soft;
   }
   public Towel(boolean absorbent){
	   this.absorbent=absorbent;
   }
   public Towel(double weight){
	   this.weight=weight;
   }
   public Towel(String pattern){
	   this.pattern=pattern;
   }
   public Towel(int price){
	   this.price=price;
   }
   public Towel(String dryingSpeed){
	   this.dryingSpeed=dryingSpeed;
   }
   
}

   
	   