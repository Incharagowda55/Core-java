class Gun{
	
	int gunId;
	String gunName;
	String type;
	String spread;
	String firingMode;
	boolean isGrip;
	
	
	public Gun(int gunId,String gunName, String type,String spread,String firingMode,boolean isGrip){
		
		this.gunId=gunId;
		this.gunName=gunName;
		this.type=type;
		this.spread=spread;
		this.firingMode=firingMode;
		this.isGrip=isGrip;
		
	}
}
		
		
		
		
		
		
	
	
	
	
	